/* Escape text before placing it in HTML text or quoted attribute values.
   Event handlers use closures whenever they need user-provided values. */
function escapeHTML(value) {
  return String(value ?? '').replace(/[&<>"']/g, char => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
  })[char]);
}
